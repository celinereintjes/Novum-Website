def build(src: Path):
    head, body = src.read_text(encoding='utf8').split('\n\n', 1)
    meta = dict(line.split(': ', 1) for line in head.splitlines())
    out_name = src.stem + '.html'
    cur = lambda f: ' aria-current="page"' if f == out_name else ''
    nav = '\n'.join(f'    <a href="{f}"{cur(f)}>{label}</a>' for f, label in NAV)
    nav += f'\n    <a href="{SUBSTACK}" target="_blank" rel="noopener">Substack<span class="ext" aria-hidden="true">↗</span><span class="visually-hidden"> (opens in a new tab)</span></a>'
    foot_links = ''.join(f'<li><a href="{f}">{label}</a></li>' for f, label in NAV)
    li_item = f'<li><span>LinkedIn</span><a href="{LINKEDIN}" target="_blank" rel="noopener">NovUM Maastricht</a></li>' if LINKEDIN else ''
    li_foot = f'<li><a href="{LINKEDIN}" target="_blank" rel="noopener">LinkedIn</a></li>' if LINKEDIN else ''
    body = body.replace('<!--LINKEDIN_ITEM-->', li_item)
    html = LAYOUT.format(title=meta['title'], description=meta['description'], page=src.stem,
                         nav=nav, join_current=cur(JOIN), body=body.rstrip(), foot_links=foot_links,
                         linkedin_foot=li_foot)
    html = STAMP_RE.sub(stamp, html)
    (root / 'novum-site' / out_name).write_text(html, encoding='utf8')
    return out_name


STAMP_RE = re.compile(r'(href|src)="((?:css|js)/[^"?]+)(?:\?v=[0-9a-f]+)?"')


def stamp(m):
    # cache-busting: ?v=<content hash> on local css/js so browsers fetch updated files
    f = root / 'novum-site' / m.group(2)
    v = hashlib.sha1(f.read_bytes()).hexdigest()[:8] if f.exists() else '0'
    return f'{m.group(1)}="{m.group(2)}?v={v}"'


if __name__ == '__main__':
    built = [build(p) for p in sorted((root / 'pages').glob('*.html'))]
    admin = root / 'novum-site' / 'admin.html'  # not generated, but its css/js links get the same stamps
    admin.write_text(STAMP_RE.sub(stamp, admin.read_text(encoding='utf8')), encoding='utf8')
    print('built', ', '.join(built))
