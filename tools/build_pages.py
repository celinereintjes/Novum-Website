"""Builds the public pages in novum-site/ from pages/*.html and the shared layout below.

Usage: python3 tools/build_pages.py
Edit a page's content in pages/<name>.html (first lines are `title:` and `description:`,
then a blank line, then the HTML inside <main>). The header, menu and footer live here.
"""
