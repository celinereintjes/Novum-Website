"""Generates supabase/seed.sql from novum-site/js/data.js.

Usage: python3 tools/make_seed.py
data.js is a plain JS object literal (unquoted keys, single-quoted strings, // comments),
so it is converted to JSON with a few regexes before loading.
"""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
src = (root / 'novum-site/js/data.js').read_text(encoding='utf8')

body = src[src.index('{'):src.rindex('}') + 1]
body = re.sub(r'^\s*//.*$', '', body, flags=re.M)                 # line comments
body = re.sub(r"'((?:[^'\\]|\\.)*)'", lambda m: json.dumps(m.group(1)), body)  # 'str' -> "str"
body = re.sub(r'([{,]\s*)([A-Za-z_]\w*)\s*:', r'\1"\2":', body)  # key: -> "key":
body = re.sub(r',(\s*[}\]])', r'\1', body)                       # trailing commas
d = json.loads(body)


def q(v):
    if v is None:
        return 'null'
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


out = ['-- Starting content for the NovUM site. Generated by tools/make_seed.py; run after schema.sql.',
       'begin;', '']

out.append('insert into councils (id, name, short_name, sort) values')
out.append(',\n'.join(f"  ({q(c['id'])}, {q(c['name'])}, {q(c['short_name'])}, {c['sort']})" for c in d['councils']))
out.append('on conflict (id) do update set name = excluded.name, short_name = excluded.short_name, sort = excluded.sort;\n')

out.append('insert into pillars (title, summary, image_url, sort) values')
out.append(',\n'.join(f"  ({q(p['title'])}, {q(p['summary'])}, {q(p.get('image_url'))}, {p['sort']})" for p in d['pillars']) + ';\n')

pillar_title = {p['id']: p['title'] for p in d['pillars']}
out.append('insert into achievements (pillar_id, council_id, title, description, sort)')
out.append('select p.id, a.council_id, a.title, a.description, a.sort from (values')
out.append(',\n'.join(
    f"  ({q(pillar_title[a['pillar_id']])}, {q(a['council_id'])}, {q(a['title'])}, {q(a['description'])}, {i})"
    for i, a in enumerate(d['achievements'])))
out.append(') as a(pillar, council_id, title, description, sort) join pillars p on p.title = a.pillar;\n')

out.append('insert into people (kind, name, role, bio, photo_url, council_id, sort) values')
out.append(',\n'.join(
    f"  ({q(p['kind'])}, {q(p['name'])}, {q(p['role'])}, {q(p.get('bio', ''))}, {q(p.get('photo_url'))}, {q(p.get('council_id'))}, {p['sort']})"
    for p in d['people']) + ';\n')

out += ['commit;', '']
(root / 'supabase/seed.sql').write_text('\n'.join(out), encoding='utf8')
print('wrote supabase/seed.sql:', len(d['pillars']), 'pillars,', len(d['achievements']), 'achievements,', len(d['people']), 'people')
